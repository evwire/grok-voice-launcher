-- Offline test of the provider/dictation settings in voice-launcher.lua (no Hammerspoon needed):
--   lua tests/settings-test.lua
local src = assert(io.open((arg[0]:match("^(.*)/tests/") or ".") .. "/voice-launcher.lua")):read("a")
local pure = src:match("%-%- %[settings%-pure%-begin%][^\n]*\n(.-)%-%- %[settings%-pure%-end%]")
local S = assert(load(pure .. "\nreturn SETTINGS"))()
local DEF = { "grok-4.20-0309-non-reasoning", "grok-4.3" }
local fails = 0
local function check(name, cond) print((cond and "ok   " or "FAIL ") .. name); if not cond then fails = fails + 1 end end

-- provider
local p = S.provider({}, DEF)
check("default is xAI", p.apiUrl == "https://api.x.ai/v1/chat/completions" and p.keychainService == "xai-voice-launcher" and p.models[1] == DEF[1])
p = S.provider({ models = { "grok-x" } }, DEF)
check("top-level models still honoured", p.models[1] == "grok-x")
p = S.provider({ provider = { preset = "openai", models = { "gpt-4.1-mini" } } }, DEF)
check("openai preset", p.apiUrl == "https://api.openai.com/v1/chat/completions" and p.keychainService == "voicelauncher-openai" and p.name == "OpenAI")
local _, e = S.provider({ provider = "openai" }, DEF)
check("non-xAI needs models", e and e:find("models"))
_, e = S.provider({ provider = { apiUrl = "https://evil.example.com/v1/chat/completions", keychainService = "xai-voice-launcher", models = { "m" } } }, DEF)
check("xAI key never sent elsewhere", e and e:find("only be sent to api.x.ai"))
_, e = S.provider({ provider = { apiUrl = "http://example.com/v1/chat/completions", keychainService = "k", models = { "m" } } }, DEF)
check("plain http refused for remote hosts", e and e:find("https"))
p = S.provider({ provider = { preset = "ollama", models = { "llama3.2" } } }, DEF)
check("ollama on localhost needs no key", p and p.keychainService == false and p.apiUrl:find("^http://localhost:11434"))
_, e = S.provider({ provider = { apiUrl = "https://api.example.com/v1/chat/completions", keychainService = false, models = { "m" } } }, DEF)
check("remote provider needs a key", e and e:find("keychainService"))
_, e = S.provider({ provider = { apiUrl = "https://api.example.com/v1", keychainService = "a'; rm -rf ~;'", models = { "m" } } }, DEF)
check("keychain service is shell-safe", e and e:find("letters"))
_, e = S.provider({ provider = { preset = "nope" } }, DEF)
check("unknown preset refused", e and e:find("unknown"))
p = S.provider({ provider = { preset = "openai", models = { "gpt-5-mini" }, maxTokensParam = "max_completion_tokens", sendTemperature = false } }, DEF)
check("max_completion_tokens / no temperature", p.maxTokensParam == "max_completion_tokens" and p.sendTemperature == false)
_, e = S.provider({ provider = { apiUrl = "https://api.x.ai.evil.com/v1/chat/completions", keychainService = "xai-voice-launcher", models = { "m" } } }, DEF)
check("look-alike xAI host refused", e ~= nil)
_, e = S.provider({ provider = { apiUrl = "https://api.x.ai@evil.example.com/v1/chat/completions", keychainService = "xai-voice-launcher", models = { "m" } } }, DEF)
check("user@host trick refused", e ~= nil)
_, e = S.provider({ provider = { apiUrl = "https://api.x.ai:evil/v1", keychainService = "xai-voice-launcher", models = { "m" } } }, DEF)
check("bad port refused", e ~= nil)
p = S.provider({ provider = { apiUrl = "http://127.0.0.1:1234/v1/chat/completions", keychainService = false, models = { "local" } } }, DEF)
check("LM Studio style localhost:port ok", p ~= nil)

-- dictation
local d = S.dictation({}, "wispr-flow")
check("legacy default = Wispr", d.backend == "wispr" and d.start == "wispr-flow://start-hands-free")
d = S.dictation({}, nil)
check("legacy nil = none", d.kind == "none")
d = S.dictation({ dictation = "spokenly" }, nil)
check("spokenly start/stop", d.start == "spokenly://start" and d.stop == "spokenly://stop")
d = S.dictation({ dictation = { backend = "spokenly", modeId = "ABCD-1234" } }, nil)
check("spokenly mode id", d.start == "spokenly://start?mode_id=ABCD-1234")
_, e = S.dictation({ dictation = { backend = "spokenly", modeId = "x&y=1" } }, nil)
check("spokenly mode id validated", e ~= nil)
d = S.dictation({ dictation = { backend = "voiceink", hotkey = { mods = { "ctrl", "option" }, key = "V" } } }, nil)
check("voiceink hotkey", d.kind == "hotkey" and d.hotkey.key == "v" and d.hotkey.mods[2] == "alt" and d.stopByToggle)
d = S.dictation({ dictation = { backend = "macos", hotkey = { mods = {}, key = "f5" }, stop = "none" } }, nil)
check("macOS dictation on F5, no toggle stop", d.kind == "hotkey" and d.hotkey.key == "f5" and not d.stopByToggle)
_, e = S.dictation({ dictation = { backend = "voiceink", hotkey = { mods = { "shift", "cmd" }, key = "space" } } }, nil)
check("own hotkey refused", e and e:find("VoiceLauncher's own"))
_, e = S.dictation({ dictation = { backend = "voiceink", hotkey = { mods = {}, key = "d" } } }, nil)
check("bare letter refused", e ~= nil)
_, e = S.dictation({ dictation = { backend = "voiceink", hotkey = { mods = { "hyper" }, key = "d" } } }, nil)
check("unknown modifier refused", e ~= nil)
_, e = S.dictation({ dictation = "siri" }, nil)
check("unknown backend refused", e ~= nil)
d = S.dictation({ dictation = "none" }, "wispr-flow")
check("explicit none beats legacy", d.kind == "none")

if fails > 0 then print(fails .. " failed"); os.exit(1) end
print("all passed")
